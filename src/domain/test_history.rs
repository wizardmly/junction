//! Test History, as IntelliJ keeps it: each finished test run saved as
//! `<config> - yyyy.MM.dd at HHh MMm SSs.xml` in its own format
//! (`TestResultsXmlFormatter`: `<testrun>`, `<count>`s, `<root>`, nested
//! `<suite>`s and `<test>`s with their `<output>` and `<diff>`), the last
//! ten of them; the Run window's Test History popup lists them as
//! "Config (date)" and opens one again.

use chrono::NaiveDateTime;

use crate::domain::testing::{Comparison, Outcome, OutputLine, TestCase, TestResults, TestSuite};

/// IntelliJ's default `test_runner.history.size`.
pub const HISTORY_SIZE: usize = 10;

/// IntelliJ's `HISTORY_DATE_FORMAT` (`yyyy.MM.dd 'at' HH'h' mm'm' ss's'`).
const DATE_FORMAT: &str = "%Y.%m.%d at %Hh %Mm %Ss";

/// A finished run, as saved and opened again.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct SavedRun {
    /// The run configuration's name.
    pub name: String,
    pub results: TestResults,
    /// The root's console: Gradle's other output.
    pub lines: Vec<String>,
    pub duration_ms: Option<u64>,
}

/// The history file's name: the configuration's name made a file name
/// (`PathUtil.suggestFileName`), then the time.
pub fn file_name(config: &str, at: NaiveDateTime) -> String {
    let safe: String = config.chars().map(|c| if c.is_control() || "<>:\"/\\|?*".contains(c) { '_' } else { c }).collect();
    format!("{} - {}.xml", safe.trim(), at.format(DATE_FORMAT))
}

/// The popup's text for a history file: "Config (2026/10/22 14:05)", or
/// the file's name when it isn't one of ours.
pub fn presentable(file_name: &str) -> String {
    let stem = file_name.strip_suffix(".xml").unwrap_or(file_name);
    if let Some((config, date)) = stem.rsplit_once(" - ")
        && let Ok(at) = NaiveDateTime::parse_from_str(date, DATE_FORMAT)
    {
        return format!("{config} ({})", at.format("%Y/%-m/%-d %H:%M"));
    }
    stem.to_owned()
}

fn escape(text: &str, attribute: bool) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' if attribute => out.push_str("&quot;"),
            '\n' if attribute => out.push_str("&#10;"),
            '\r' if attribute => out.push_str("&#13;"),
            '\t' if attribute => out.push_str("&#9;"),
            // Not allowed in XML 1.0 at all.
            c if (c as u32) < 0x20 && !matches!(c, '\n' | '\r' | '\t') => {}
            c => out.push(c),
        }
    }
    out
}

fn status(outcome: Outcome) -> &'static str {
    match outcome {
        Outcome::Passed => "passed",
        Outcome::Failed => "failed",
        Outcome::Error => "error",
        Outcome::Ignored => "ignored",
        // Never finished: IntelliJ's magnitudes 0, 2 and 4.
        Outcome::Running | Outcome::Terminated => "skipped",
    }
}

fn outcome(status: &str) -> Outcome {
    match status {
        "passed" => Outcome::Passed,
        "failed" => Outcome::Failed,
        "error" => Outcome::Error,
        "ignored" => Outcome::Ignored,
        _ => Outcome::Terminated,
    }
}

/// `<output>` elements: consecutive lines of one stream in one element.
fn write_output(out: &mut String, indent: &str, lines: &[OutputLine]) {
    let mut start = 0;
    while start < lines.len() {
        let stderr = lines[start].stderr;
        let end = lines[start..].iter().position(|l| l.stderr != stderr).map_or(lines.len(), |n| start + n);
        let text: String = lines[start..end].iter().map(|l| format!("{}\n", l.text)).collect();
        out.push_str(&format!("{indent}<output type=\"{}\">{}</output>\n", if stderr { "stderr" } else { "stdout" }, escape(&text, false)));
        start = end;
    }
}

/// The run in IntelliJ's format; `footer` is its `footerText`
/// ("Generated by Junction Studio on …").
pub fn to_xml(run: &SavedRun, footer: &str) -> String {
    let mut counts: Vec<(&str, usize)> = Vec::new();
    let tests = || run.results.suites.iter().flat_map(|s| &s.tests);
    for test in tests() {
        let name = status(test.outcome);
        match counts.iter_mut().find(|(n, _)| *n == name) {
            Some((_, count)) => *count += 1,
            None => counts.push((name, 1)),
        }
    }
    counts.sort();
    counts.insert(0, ("total", tests().count()));

    let mut out = String::from("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
    let duration = run.duration_ms.map(|d| format!(" duration=\"{d}\"")).unwrap_or_default();
    out.push_str(&format!("<testrun name=\"{}\"{duration} footerText=\"{}\">\n", escape(&run.name, true), escape(footer, true)));
    for (name, value) in counts {
        out.push_str(&format!("    <count name=\"{name}\" value=\"{value}\"/>\n"));
    }
    out.push_str(&format!("    <config configId=\"GradleRunConfiguration\" name=\"{}\"/>\n", escape(&run.name, true)));
    if run.lines.is_empty() {
        out.push_str("    <root name=\"Test Results\"/>\n");
    } else {
        out.push_str("    <root name=\"Test Results\">\n");
        let lines: Vec<OutputLine> = run.lines.iter().map(|l| OutputLine { text: l.clone(), stderr: false }).collect();
        write_output(&mut out, "        ", &lines);
        out.push_str("    </root>\n");
    }
    for suite in &run.results.suites {
        let duration = suite.duration_ms().map(|d| format!(" duration=\"{d}\"")).unwrap_or_default();
        out.push_str(&format!(
            "    <suite name=\"{}\" status=\"{}\"{duration} locationUrl=\"java:suite://{}\">\n",
            escape(&suite.simple_name(), true),
            status(suite.outcome()),
            escape(&suite.class, true)
        ));
        write_output(&mut out, "        ", &suite.output);
        for test in &suite.tests {
            let duration = test.duration_ms.map(|d| format!(" duration=\"{d}\"")).unwrap_or_default();
            let location = format!("java:test://{}/{}", suite.class, test.id);
            out.push_str(&format!(
                "        <test name=\"{}\" status=\"{}\"{duration} locationUrl=\"{}\">\n",
                escape(&test.name, true),
                status(test.outcome),
                escape(&location, true)
            ));
            write_output(&mut out, "            ", &test.output);
            if let Some(c) = &test.comparison {
                out.push_str(&format!("            <diff expected=\"{}\" actual=\"{}\"/>\n", escape(&c.expected, true), escape(&c.actual, true)));
            }
            // The exception last, as IntelliJ prints its error message and
            // stack trace after the test's own output.
            if let Some(failure) = &test.failure {
                out.push_str(&format!("            <output type=\"stderr\">{}</output>\n", escape(&format!("{}\n", failure.trim_end()), false)));
            }
            out.push_str("        </test>\n");
        }
        out.push_str("    </suite>\n");
    }
    out.push_str("</testrun>\n");
    out
}

/// Each `<output>` element's lines.
fn lines_of(node: roxmltree::Node) -> Vec<Vec<OutputLine>> {
    node.children()
        .filter(|c| c.has_tag_name("output"))
        .map(|c| {
            let stderr = c.attribute("type") == Some("stderr");
            c.text().unwrap_or_default().lines().map(|text| OutputLine { text: text.to_owned(), stderr }).collect()
        })
        .collect()
}

fn read_test(node: roxmltree::Node, class: &str) -> TestCase {
    let name = node.attribute("name").unwrap_or_default().to_owned();
    let id = node
        .attribute("locationUrl")
        .and_then(|l| l.split_once("://"))
        .and_then(|(_, rest)| rest.strip_prefix(class).and_then(|r| r.strip_prefix('/')).or(Some(rest).filter(|r| !r.contains('/'))))
        .map(str::to_owned)
        .unwrap_or_else(|| name.clone());
    let outcome = outcome(node.attribute("status").unwrap_or("passed"));
    let mut output: Vec<OutputLine> = Vec::new();
    let mut failure = None;
    let blocks = lines_of(node);
    let count = blocks.len();
    for (ix, lines) in blocks.into_iter().enumerate() {
        // A failed test's last stderr block is its exception.
        if ix + 1 == count && outcome.is_failure() && lines.first().is_some_and(|l| l.stderr) {
            failure = Some(lines.iter().map(|l| l.text.as_str()).collect::<Vec<_>>().join("\n"));
        } else {
            output.extend(lines);
        }
    }
    let comparison = node.children().find(|c| c.has_tag_name("diff")).map(|d| Comparison { expected: d.attribute("expected").unwrap_or_default().to_owned(), actual: d.attribute("actual").unwrap_or_default().to_owned() });
    TestCase { name, id, outcome, duration_ms: node.attribute("duration").and_then(|d| d.parse().ok()), output, failure, comparison }
}

/// The suites under a node: a suite holding tests is a test class (named
/// by its location, else its name); suites of suites are walked into.
fn read_suites(node: roxmltree::Node, out: &mut Vec<TestSuite>) {
    for child in node.children().filter(|c| c.is_element()) {
        match child.tag_name().name() {
            "suite" => {
                let class = child.attribute("locationUrl").and_then(|l| l.split_once("://")).map(|(_, c)| c.to_owned()).unwrap_or_else(|| child.attribute("name").unwrap_or_default().to_owned());
                let tests: Vec<TestCase> = child.children().filter(|c| c.has_tag_name("test")).map(|t| read_test(t, &class)).collect();
                if !tests.is_empty() {
                    let output = lines_of(child).into_iter().flatten().collect();
                    out.push(TestSuite { class, tests, output });
                }
                read_suites(child, out);
            }
            // Tests right under the run, without a class.
            "test" if node.has_tag_name("testrun") => {
                let test = read_test(child, "");
                match out.iter_mut().find(|s| s.class.is_empty()) {
                    Some(suite) => suite.tests.push(test),
                    None => out.push(TestSuite { class: String::new(), tests: vec![test], output: Vec::new() }),
                }
            }
            _ => {}
        }
    }
}

/// A run saved in IntelliJ's format (by Junction or by IntelliJ); none
/// for anything else.
pub fn from_xml(xml: &str) -> Option<SavedRun> {
    let doc = roxmltree::Document::parse(xml).ok()?;
    let run = doc.root_element();
    if !run.has_tag_name("testrun") {
        return None;
    }
    let mut suites = Vec::new();
    read_suites(run, &mut suites);
    let lines = run.children().find(|c| c.has_tag_name("root")).map(|r| lines_of(r).into_iter().flatten().map(|l| l.text).collect()).unwrap_or_default();
    Some(SavedRun { name: run.attribute("name").unwrap_or_default().to_owned(), results: TestResults { suites }, lines, duration_ms: run.attribute("duration").and_then(|d| d.parse().ok()) })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> SavedRun {
        let line = |text: &str, stderr| OutputLine { text: text.into(), stderr };
        let failed = TestCase {
            name: "adds".into(),
            id: "adds".into(),
            outcome: Outcome::Failed,
            duration_ms: Some(12),
            output: vec![line("computing <1 & 2>", false), line("warn", true), line("done", false)],
            failure: Some("java.lang.AssertionError: expected:<4> but was:<5>\n\tat a.ATest.adds(ATest.kt:9)".into()),
            comparison: Some(Comparison { expected: "4".into(), actual: "5\n\"x\"".into() }),
        };
        let passed = TestCase { name: "[1] 2, 3".into(), id: "twice(int)[1]".into(), outcome: Outcome::Passed, duration_ms: Some(3), output: vec![], failure: None, comparison: None };
        let skipped = TestCase { name: "later".into(), id: "later".into(), outcome: Outcome::Ignored, duration_ms: None, output: vec![], failure: None, comparison: None };
        SavedRun {
            name: "ATest".into(),
            results: TestResults { suites: vec![TestSuite { class: "a.ATest".into(), tests: vec![failed, passed, skipped], output: vec![line("setUp", false)] }] },
            lines: vec!["> Task :app:testDebugUnitTest".into(), "BUILD FAILED".into()],
            duration_ms: Some(1500),
        }
    }

    #[test]
    fn round_trip() {
        let run = sample();
        let xml = to_xml(&run, "Generated by Junction Studio");
        assert!(xml.contains("<count name=\"total\" value=\"3\"/>\n    <count name=\"failed\" value=\"1\"/>\n    <count name=\"ignored\" value=\"1\"/>\n    <count name=\"passed\" value=\"1\"/>"), "{xml}");
        assert!(xml.contains("<suite name=\"ATest\" status=\"failed\" duration=\"15\" locationUrl=\"java:suite://a.ATest\">"), "{xml}");
        assert_eq!(from_xml(&xml), Some(run));
    }

    #[test]
    fn reads_intellij_exports() {
        let xml = r#"<?xml version="1.0" encoding="UTF-8"?><testrun duration="20" footerText="Generated by IntelliJ IDEA" name="All in core">
    <count name="total" value="2"/><count name="failed" value="1"/><count name="passed" value="1"/>
    <config configId="JUnit" factoryName="JUnit" name="All in core"><module name="core"/></config>
    <root comment="core" name="&lt;default package&gt;" location="java:suite://&lt;default package&gt;"/>
    <suite duration="20" locationUrl="java:suite://com.x.CalcTest" name="CalcTest" status="failed">
        <test duration="5" locationUrl="java:test://com.x.CalcTest/sum" name="sum()" status="passed">
            <output type="stdout">hello&#10;</output>
        </test>
        <test duration="15" locationUrl="java:test://com.x.CalcTest/div" name="div()" status="failed">
            <diff actual="5" expected="4"/>
            <output type="stderr">org.opentest4j.AssertionFailedError: boom&#10;	at com.x.CalcTest.div(CalcTest.java:12)&#10;</output>
        </test>
    </suite>
</testrun>"#;
        let run = from_xml(xml).unwrap();
        assert_eq!(run.name, "All in core");
        assert_eq!(run.duration_ms, Some(20));
        let suite = &run.results.suites[0];
        assert_eq!(suite.class, "com.x.CalcTest");
        assert_eq!((suite.tests[0].id.as_str(), suite.tests[0].output.len()), ("sum", 1));
        assert_eq!(suite.tests[1].failure.as_deref(), Some("org.opentest4j.AssertionFailedError: boom\n\tat com.x.CalcTest.div(CalcTest.java:12)"));
        assert_eq!(suite.tests[1].comparison, Some(Comparison { expected: "4".into(), actual: "5".into() }));
        assert!(from_xml("<testsuite/>").is_none());
    }

    #[test]
    fn names() {
        let at = NaiveDateTime::parse_from_str("2026-10-22 14:05:09", "%Y-%m-%d %H:%M:%S").unwrap();
        let name = file_name("ATest.adds: a/b", at);
        assert_eq!(name, "ATest.adds_ a_b - 2026.10.22 at 14h 05m 09s.xml");
        assert_eq!(presentable(&name), "ATest.adds_ a_b (2026/10/22 14:05)");
        assert_eq!(presentable("results.xml"), "results");
    }
}
