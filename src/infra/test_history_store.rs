//! Test History on disk: `<cache>/test-history/<project>-<hash>/`, one
//! IntelliJ-format XML file per finished run, the newest ten kept.

use std::path::{Path, PathBuf};
use std::time::SystemTime;

use crate::domain::test_history::{self, HISTORY_SIZE, SavedRun};
use crate::domain::testing::TestSuite;
use crate::index::libraries::{cache_dir, stable_hash};

pub struct TestHistoryStore {
    dir: PathBuf,
}

impl TestHistoryStore {
    pub fn for_project(root: &Path) -> Option<Self> {
        let name = root.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
        Some(Self { dir: cache_dir()?.join("test-history").join(format!("{name}-{:016x}", stable_hash(&root.to_string_lossy()))) })
    }

    #[cfg(test)]
    pub fn at(dir: PathBuf) -> Self {
        Self { dir }
    }

    /// Saves a finished run, then drops the oldest beyond ten.
    pub fn save(&self, run: &SavedRun) -> Result<PathBuf, String> {
        std::fs::create_dir_all(&self.dir).map_err(|e| e.to_string())?;
        let now = chrono::Local::now();
        let path = self.dir.join(test_history::file_name(&run.name, now.naive_local()));
        let footer = format!("Generated by Junction Studio on {}", now.format("%Y/%-m/%-d %H:%M"));
        std::fs::write(&path, test_history::to_xml(run, &footer)).map_err(|e| e.to_string())?;
        for (old, _) in self.entries().into_iter().skip(HISTORY_SIZE) {
            let _ = std::fs::remove_file(old);
        }
        Ok(path)
    }

    /// The saved runs, newest first: each file and its popup text.
    pub fn list(&self) -> Vec<(PathBuf, String)> {
        self.entries().into_iter().take(HISTORY_SIZE).map(|(path, _)| {
            let label = test_history::presentable(&path.file_name().unwrap_or_default().to_string_lossy());
            (path, label)
        }).collect()
    }

    fn entries(&self) -> Vec<(PathBuf, SystemTime)> {
        let Ok(dir) = std::fs::read_dir(&self.dir) else { return Vec::new() };
        let mut out: Vec<(PathBuf, SystemTime)> = dir
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|e| e == "xml"))
            .filter_map(|p| {
                let modified = p.metadata().and_then(|m| m.modified()).ok()?;
                Some((p, modified))
            })
            .collect();
        out.sort_by(|a, b| b.1.cmp(&a.1).then_with(|| b.0.cmp(&a.0)));
        out
    }
}

/// Import Tests from File: a run in IntelliJ's format, or a JUnit XML
/// report (named after the file).
pub fn import(path: &Path) -> Result<SavedRun, String> {
    let xml = std::fs::read_to_string(path).map_err(|e| e.to_string())?;
    if let Some(run) = test_history::from_xml(&xml) {
        return Ok(run);
    }
    let suites: Vec<TestSuite> = crate::infra::gradle_tests::parse_report(&xml);
    if suites.is_empty() {
        return Err(format!("{} contains no test results.", path.file_name().unwrap_or_default().to_string_lossy()));
    }
    let name = path.file_stem().unwrap_or_default().to_string_lossy().trim_start_matches("TEST-").to_owned();
    let results = crate::domain::testing::TestResults { suites };
    let duration_ms = results.duration_ms();
    Ok(SavedRun { name, results, lines: Vec::new(), duration_ms })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keeps_the_newest_ten() {
        let dir = std::env::temp_dir().join(format!("junction-test-history-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        let store = TestHistoryStore::at(dir.clone());
        for ix in 0..12 {
            std::fs::create_dir_all(&dir).unwrap();
            let old = dir.join(format!("Old{ix:02} - 2026.10.01 at 10h 00m {ix:02}s.xml"));
            std::fs::write(&old, "<testrun/>").unwrap();
            let at = SystemTime::now() - std::time::Duration::from_secs(100 - ix);
            std::fs::File::options().write(true).open(&old).unwrap().set_modified(at).unwrap();
        }
        let run = SavedRun { name: "ATest".into(), ..Default::default() };
        let saved = store.save(&run).unwrap();
        let list = store.list();
        assert_eq!(list.len(), HISTORY_SIZE);
        assert_eq!(list[0].0, saved);
        assert!(list[0].1.starts_with("ATest ("));
        assert_eq!(std::fs::read_dir(&dir).unwrap().count(), HISTORY_SIZE);
        assert_eq!(import(&saved).unwrap().name, "ATest");
        let junit = dir.join("TEST-a.BTest.xml");
        std::fs::write(&junit, r#"<testsuite name="a.BTest"><testcase name="b" classname="a.BTest" time="0.01"/></testsuite>"#).unwrap();
        let imported = import(&junit).unwrap();
        assert_eq!((imported.name.as_str(), imported.results.suites[0].tests[0].duration_ms), ("a.BTest", Some(10)));
        assert!(import(&dir.join("missing.xml")).is_err());
        std::fs::remove_dir_all(&dir).unwrap();
    }
}
